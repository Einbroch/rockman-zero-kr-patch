def translate(i, t):
    if i in FIXED:
        return FIXED[i]
    m = re.match(r'\{F3:02\}\{FB\}(.*)の体力が\n\{F2\}(\d+)\{F1\}ふえました\{end\}$', t)
    if m:
        return f'{{F3:02}}{{FB}}{ENEMY[m[1]]}의 체력이\n{{F2}}{m[2]}{{F1}} 늘었습니다{{end}}'
    m = re.match(r'\{F3:02\}\{FB\}(.*?)\n?コウゲキりょくが\nつうじょう時より\{F2\}(\d+)\{F1\}ふえました\{end\}$', t, re.S)
    if m:
        a = re.match(r'アニマル系エルフの(.*)と\n(.*)の$', m[1])
        if a:
            return (f'{{F3:02}}{{FB}}애니멀 계열 엘프 {ANIMAL[a[1]]}와\n{ANIMAL[a[2]]}의 공격력이\n'
                    f'평소보다 {{F2}}{m[2]}{{F1}} 늘었습니다{{end}}')
        return f'{{F3:02}}{{FB}}{WEAP[m[1].rstrip("の")]}의 공격력이\n평소보다 {{F2}}{m[2]}{{F1}} 늘었습니다{{end}}'
    m = re.match(r'\{F3:02\}\{FB\}\{F2\}(.*)\{F1\}のミニゲームが ツイカされました\{end\}$', t)
    if m:
        return f'{{F3:02}}{{FB}}{{F2}}{MINI[m[1]]}{{F1}} 미니게임이 추가되었습니다{{end}}'
    raise ValueError(f'no rule for {i}: {t!r}')


