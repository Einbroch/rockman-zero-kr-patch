def has_final(word):
    """마지막 글자에 받침이 있는가(한글이 아니면 영숫자 발음으로 판단)."""
    last = word.rstrip()[-1]
    if '가' <= last <= '힣':
        return (ord(last) - 0xAC00) % 28 != 0
    return last.upper() in 'LMNR0136789'


def josa(word, pair):
    """pair 예: '이가', '을를', '은는', '과와'"""
    return pair[0] if has_final(word) else pair[1]
